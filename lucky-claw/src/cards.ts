export function drawStyleCard(brand: string, previous?: StyleCard, random = Math.random): StyleCard {
  const options = writing[brand] ?? [['오늘의 태도', '작은 기쁨을 챙기기', '오늘 마음에 들었던 순간을 하나 기억해두세요. 평범한 하루에도 내 것이 되는 장면이 있어요.']];
  const pool = options.filter(row => row[1] !== previous?.title);
  const [category,title,message] = pool[Math.min(pool.length - 1, Math.max(0, Math.floor(random() * pool.length)))];
  return {brand,category,title,message};
}

